_COMPILED = [(d, t, re.compile(p)) for d, t, p in RULES]


def _catalog() -> dict[str, set[str]]:
    data = json.loads(TAGS_FILE.read_text(encoding="utf-8"))
    return {d["id"]: set(d["tags"]) for d in data["domains"]}


def classify(*parts: str) -> tuple[str, list[str]]:
    """제목·요약을 받아 (대분류, [세부태그]) 를 낸다. 못 고르면 ("", [])."""
    text = " ".join(p for p in parts if p)
    if not text:
        return "", []
    for domain, tag, pattern in _COMPILED:
        if pattern.search(text):
            return domain, [tag]
    return "", []


